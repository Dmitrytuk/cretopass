#!/usr/bin/env python3
"""Regenerate the root ``LICENSE-THIRD-PARTY`` summary from the crate graph.

The summary lists every crate that can end up compiled into a released
binary -- normal and build dependencies of the workspace member, across all
supported targets (dev-dependencies are excluded) -- grouped by the raw SPDX
license expression Cargo reports. Crates distributed under a license that
requires its notice and/or text to accompany binary distributions
(``BSD-3-Clause``, ``Apache-2.0``) get a full-text block appended.

Usage::

    scripts/gen-third-party-licenses.py            # rewrite LICENSE-THIRD-PARTY
    scripts/gen-third-party-licenses.py --check    # exit 1 if the file is stale

The generated file is deterministic: it depends only on ``cargo metadata
--locked`` output and the crate sources in the local registry. Run ``cargo
fetch`` first if the sources for a target you do not build are missing.
"""

from __future__ import annotations

import json
import pathlib
import re
import subprocess
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "LICENSE-THIRD-PARTY"
LICENSE_TEXTS = REPO_ROOT / "scripts" / "license-texts"

WORKSPACE_CRATE = "cretopass"

# License expressions that require their full text to travel with a binary
# distribution. Matched exactly against Cargo's license field, so a crate
# offering a permissive alternative (e.g. "MIT OR Apache-2.0") is not forced
# into this set -- for those, the most permissive option is selected and only
# that option's obligations apply (see the notes at the end of the file).
ATTRIBUTION_LICENSES = ["BSD-3-Clause", "Apache-2.0"]

HEADER = """\
cretopass -- Third-Party License Summary
========================================

cretopass is licensed under the MIT License (see LICENSE).

This file lists all direct and transitive (normal and build) crate
dependencies for all supported targets, along with their license identifiers
(SPDX). All dependencies are available under permissive licenses compatible
with MIT. Where a crate is offered under multiple licenses, the MIT (or
otherwise most permissive) option is selected for use in this project.

For the full license text of each crate, see its source repository or the
vendored copy under ~/.cargo/registry/src/ after building with Cargo."""

ATTRIBUTION_INTRO = """\
Licenses requiring attribution
==============================

The crates below are distributed under licenses whose terms require their
copyright notice and/or license text to be reproduced in binary
distributions. The full license text follows.

"""

NOTES = """\
Notes on dual-licensed crates
=============================

  - self_cell: offered under "Apache-2.0 OR GPL-2.0-only" (v1.x) and
    Apache-2.0 (v0.10). The Apache-2.0 option is selected. GPL is NOT
    triggered by this use.
  - r-efi: offered under "MIT OR Apache-2.0 OR LGPL-2.1-or-later".
    The MIT option is selected.
  - ryu: offered under "Apache-2.0 OR BSL-1.0". Either is permissive; the
    Apache-2.0 text is reproduced above.
  - clipboard-win, error-code: licensed solely under BSL-1.0 (Boost Software
    License). BSL-1.0 explicitly waives its notice requirement for
    "machine-executable object code generated by a source language
    processor", which is exactly what the released binaries are, so no
    further attribution is required.
  - unicode-ident: "(MIT OR Apache-2.0) AND Unicode-3.0". The MIT option
    is selected; Unicode-3.0 is permissive.
  - fiat-crypto: "MIT OR Apache-2.0 OR BSD-1-Clause". The MIT option is
    selected.
  - memchr, same-file, walkdir, winapi-util: "Unlicense OR MIT". Either
    option is permissive; MIT is selected.
  - foldhash, tinyvec: Zlib option available; MIT/Apache-2.0 selected
    where offered."""


def cargo_metadata() -> dict:
    """Return parsed ``cargo metadata --locked`` output for this workspace."""
    result = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1"],
        cwd=REPO_ROOT,
        check=True,
        capture_output=True,
        text=True,
    )
    return json.loads(result.stdout)


def non_dev_packages(meta: dict) -> list[dict]:
    """Every crate reachable through normal/build edges, all targets, no dev."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    roots = [
        p["id"]
        for p in meta["packages"]
        if p["name"] == WORKSPACE_CRATE and p.get("source") is None
    ]
    if not roots:
        raise SystemExit(f"workspace crate {WORKSPACE_CRATE!r} not found")

    seen: set[str] = set()
    stack = list(roots)
    while stack:
        pkg_id = stack.pop()
        if pkg_id in seen:
            continue
        seen.add(pkg_id)
        for dep in nodes[pkg_id]["deps"]:
            kinds = {kind["kind"] or "normal" for kind in dep["dep_kinds"]}
            if kinds <= {"dev"}:
                continue
            stack.append(dep["pkg"])
    return [packages[pkg_id] for pkg_id in seen]


def version_key(version: str) -> tuple:
    """Sort key that orders ``0.4.15`` before ``0.12.1`` (not lexicographically)."""
    key = []
    for part in re.split(r"[.+-]", version):
        key.append((0, int(part)) if part.isdigit() else (1, part))
    return tuple(key)


def by_name_version(packages: list[dict]) -> list[dict]:
    return sorted(packages, key=lambda p: (p["name"], version_key(p["version"])))


def heading(text: str) -> list[str]:
    return [text, "-" * len(text)]


def copyright_lines(pkg: dict) -> list[str]:
    """Leading ``Copyright ...`` lines from the crate's own LICENSE file."""
    crate_dir = pathlib.Path(pkg["manifest_path"]).parent
    candidates = sorted(
        path
        for path in crate_dir.iterdir()
        if path.is_file() and path.name.lower().startswith("license")
    )
    for path in candidates:
        # Only the leading notice block is a real copyright notice; later
        # "Copyright ..." lines (e.g. the Apache-2.0 appendix placeholder) are
        # template text, not attribution.
        notice: list[str] = []
        started = False
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            stripped = line.strip()
            if not stripped:
                if started:
                    break
                continue
            started = True
            if stripped.startswith("Copyright"):
                notice.append(stripped)
        if notice:
            return notice
    return []


def license_body(name: str) -> list[str]:
    path = LICENSE_TEXTS / f"{name}.txt"
    return path.read_text(encoding="utf-8").rstrip("\n").splitlines()


def render(meta: dict) -> str:
    by_expression: dict[str, list[dict]] = {}
    for pkg in non_dev_packages(meta):
        expression = pkg.get("license")
        if not expression:
            raise SystemExit(f"{pkg['name']} has no SPDX license expression")
        by_expression.setdefault(expression, []).append(pkg)

    lines = HEADER.splitlines()
    lines += ["", ""]
    for expression in sorted(by_expression):
        lines += heading(expression)
        lines.append("")
        lines += [
            f"  - {p['name']} {p['version']}"
            for p in by_name_version(by_expression[expression])
        ]
        lines += ["", ""]

    # Attribution: a crate list per license, then each license's full text.
    lines.append("")
    lines += ATTRIBUTION_INTRO.splitlines()
    attributed: dict[str, list[dict]] = {}
    for expression in ATTRIBUTION_LICENSES:
        members = by_name_version(by_expression.get(expression, []))
        if not members:
            continue
        attributed[expression] = members
        lines += heading(expression)
        lines.append("")
        for pkg in members:
            lines.append(f"  - {pkg['name']} {pkg['version']}")
            notice = copyright_lines(pkg)
            if not notice and expression == "BSD-3-Clause":
                sys.stderr.write(
                    f"warning: no copyright notice found for {pkg['name']} "
                    f"{pkg['version']}; run `cargo fetch`\n"
                )
            lines += [f"      {line}" for line in notice]
        lines.append("")

    for expression in attributed:
        lines += heading(f"{expression} (full text)")
        lines.append("")
        lines += license_body(expression)
        lines.append("")

    lines.append("")
    lines += NOTES.splitlines()

    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    rendered = render(cargo_metadata())

    if check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != rendered:
            sys.stderr.write(
                "LICENSE-THIRD-PARTY is out of date; "
                "run scripts/gen-third-party-licenses.py\n"
            )
            return 1
        return 0

    OUTPUT.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
